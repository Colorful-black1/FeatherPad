export function describeFileIcon(name: string): FileIconDescription {
  const lower = name.toLocaleLowerCase();
  const exact = exactFiles[lower];
  if (exact) return exact;
  if (lower.startsWith('.env')) return { shape: 'gear', color: 'yellow' };
  const dot = lower.lastIndexOf('.');
  const extension = dot > 0 && dot < lower.length - 1 ? lower.slice(dot + 1) : '';
  return byExtension[extension] ?? { shape: 'text', color: 'grey' };
}
