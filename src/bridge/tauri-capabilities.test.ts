import { readFileSync, existsSync } from 'node:fs';
import { describe, expect, it } from 'vitest';

const root = new URL('../../', import.meta.url);

describe('Tauri command capabilities', () => {
  it('allows every app command registered in the native handler', () => {
    const source = readFileSync(new URL('src-tauri/src/lib.rs', root), 'utf8');
    const block = source.split('generate_handler![')[1]?.split(']')[0];
    expect(block).toBeTruthy();
    const commands = [...(block ?? '').matchAll(/commands::[a-z_]+::([a-z_]+)/g)].map(match => match[1]!);
    expect(commands.length).toBeGreaterThan(0);

    const capability = JSON.parse(readFileSync(new URL('src-tauri/capabilities/main.json', root), 'utf8')) as {
      permissions: string[];
    };
    const missing = commands.filter(command => !capability.permissions.includes(`allow-${command.replaceAll('_', '-')}`));
    expect(missing).toEqual([]);

    for (const command of commands) {
      expect(existsSync(new URL(`src-tauri/permissions/autogenerated/${command}.toml`, root)),
        `missing permission definition for ${command}`).toBe(true);
    }
  });
});
